import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const calls=[];
const listeners={};
const classes=new Set();
const element={classList:{contains:k=>classes.has(k),toggle(k,v){v?classes.add(k):classes.delete(k)}},setAttribute(){},style:{setProperty(){}},addEventListener(k,f){listeners[k]=f},contains:()=>true,querySelector:()=>null,clientWidth:980};
const document={addEventListener(){},getElementById:()=>element,querySelector:s=>s==='.app-viewport'?element:null,querySelectorAll:()=>[],documentElement:{classList:{add(){},toggle(){}}}};
const window={scrollBy:options=>calls.push(options.top),innerWidth:1470,innerHeight:900,matchMedia:q=>({matches:!q.includes('reduced'),addEventListener(){}}),addEventListener(){}};
const demo={mountDemo:()=>({showStep:s=>calls.push(s),setMode:m=>calls.push(m),reset(){}})};
let source=await readFile(new URL('../assets/story.js',import.meta.url),'utf8');
source=source.replace('await import("./demo.js").catch(() => null)','fakeDemo');
const run=new (Object.getPrototypeOf(async function(){}).constructor)('document','window','fakeDemo','requestAnimationFrame',source+'\nreturn {enterExplore,onScrollChapter,previewRequest,focusScale};');
const story=await run(document,window,demo,()=>1);
story.enterExplore(true);
listeners.focusin();
calls.length=0;
story.onScrollChapter('notes');
assert.ok(calls.includes('notes'),'Scrolling must advance the app after Explore, even with focus inside it');
story.previewRequest('quiz');
calls.length=0;
story.onScrollChapter('flashcards');
assert.ok(calls.includes('flashcards'),'Scrolling backward must leave a manually selected chapter');
calls.length=0;
let prevented=false;
listeners.wheel({deltaY:120,deltaX:0,deltaMode:0,preventDefault(){prevented=true}});
assert.equal(prevented,true);
assert.ok(calls.includes(120),'Wheel over the laptop scrolls the story page');
classes.add('demo-expanded');
calls.length=0;prevented=false;
listeners.wheel({deltaY:120,deltaX:0,deltaMode:0,preventDefault(){prevented=true}});
assert.equal(prevented,false,'Expanded app retains its own scrolling');
console.log('PASS: scroll resumes story after exploration, focused controls, and manual chapter selection.');

assert.equal(story.focusScale(600,5000,650,900),1);
assert.equal(story.focusScale(100,5000,650,900),1.15);
assert.equal(story.focusScale(100,750,650,900),1);
